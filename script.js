        function setupVideoPlayers() {
          document.querySelectorAll('.video-project-container').forEach(container => {
            const video = container.querySelector('.project-video');
            const playPauseBtn = container.querySelector('.video-play-pause');
            const muteBtn = container.querySelector('.video-mute');
            const playIcon = playPauseBtn.querySelector('.play-icon');
            const pauseIcon = playPauseBtn.querySelector('.pause-icon');
            const muteIcon = muteBtn.querySelector('.mute-icon');
            const unmuteIcon = muteBtn.querySelector('.unmute-icon');

            function updateIcons(isPlaying, isMuted) {
              playIcon.classList.toggle('hidden', isPlaying);
              pauseIcon.classList.toggle('hidden', !isPlaying);
              muteIcon.classList.toggle('hidden', !isMuted);
              unmuteIcon.classList.toggle('hidden', isMuted);
            }

            function activateVideo() {
              if (activeVideo && activeVideo !== video) {
                activeVideo.pause();
                activeVideo.currentTime = 0;
                activeVideo.muted = true;
              }
              activeVideo = video;
            }

            // AUTOPLAY ON HOVER (MUTED)
            container.addEventListener('mouseenter', () => {
              activateVideo();
              video.muted = true;
              video.play();
              updateIcons(true, true);
            });

            // Stop when leaving hover
            container.addEventListener('mouseleave', () => {
              video.pause();
              video.currentTime = 0;
              video.muted = true;
              updateIcons(false, true);
              if (activeVideo === video) activeVideo = null;
            });

            //  Play / Pause button
            playPauseBtn.addEventListener('click', e => {
              e.stopPropagation();

              if (video.paused) {
                activateVideo();
                video.muted = true;
                video.play();
                updateIcons(true, true);
              } else {
                video.pause();
                video.currentTime = 0;
                video.muted = true;
                updateIcons(false, true);
                activeVideo = null;
              }
            });

            //  Mute toggle (GLOBAL audio lock)
            muteBtn.addEventListener('click', e => {
              e.stopPropagation();

              activateVideo();

              const unmute = video.muted;

              document.querySelectorAll('video').forEach(v => (v.muted = true));

              video.muted = !unmute;
              updateIcons(!video.paused, video.muted);
            });

            // â¹ Stop after one full play
            video.addEventListener('ended', () => {
              video.currentTime = 0;
              video.muted = true;
              updateIcons(false, true);
              activeVideo = null;
            });
          });
        }




